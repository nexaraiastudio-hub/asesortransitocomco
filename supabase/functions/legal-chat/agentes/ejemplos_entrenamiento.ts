// Genera un texto formateado con todos los ejemplos para inyectar en el system prompt del redactor
export function generarEjemplosParaRedactor(): string {
  return TODOS_LOS_EJEMPLOS.map((ej, i) => {
    const partes = [];
    partes.push(`=== EJEMPLO ${i + 1}: ${ej.nombre} ===`);

    partes.push(`USUARIO: "${ej.fase1_usuario}"`);
    partes.push(`RESPUESTA CORRECTA FASE 1:\n${ej.fase1_respuesta}`);

    partes.push(`USUARIO: "${ej.fase2_usuario}"`);
    partes.push(`RESPUESTA CORRECTA FASE 2:\n${ej.fase2_respuesta}`);

    // Fase 2b: refutación de afirmación del oficial (solo en algunos ejemplos)
    if ('fase2b_usuario' in ej && 'fase2b_respuesta' in ej) {
      const ejConRefutacion = ej as typeof EJEMPLO_2_POLARIZADOS_ESCOLAR;
      partes.push(`USUARIO (reporta AFIRMACIÓN del oficial, NO insistencia): "${ejConRefutacion.fase2b_usuario}"`);
      partes.push(`RESPUESTA CORRECTA FASE 2b (REFUTACIÓN — NO es Fase 3, NO escala):\n${ejConRefutacion.fase2b_respuesta}`);
    }

    if ('fase3_usuario' in ej && 'fase3_respuesta' in ej) {
      const ejCompleto = ej as typeof EJEMPLO_1_LLANTAS;
      partes.push(`USUARIO: "${ejCompleto.fase3_usuario}"`);
      partes.push(`RESPUESTA CORRECTA FASE 3:\n${ejCompleto.fase3_respuesta}`);
    }

    return partes.join("\n\n");
  }).join("\n\n" + "─".repeat(60) + "\n\n");
}
